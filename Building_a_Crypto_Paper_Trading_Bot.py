# Create Coin Data Model
class Coin(Base):
    __tablename__ = "coins"
    id = Column(Integer, primary_key=True, autoincrement=True)
    coin_id = Column(String, unique=True, nullable=False)
    symbol = Column(String, unique=True, nullable=False)
    realized_pnl = Column(Float, nullable=True)
    prices = relationship(
        "CoinPrice", back_populates="coin", cascade="all, delete-orphan"
    )
class CoinPrice(Base):
    __tablename__ = "coins_prices"
    id = Column(Integer, primary_key=True, autoincrement=True)
    symbol = Column(String, ForeignKey("coins.symbol"), nullable=False)
    timestamp = Column(DateTime, nullable=False)
    value = Column(Float, nullable=False)
    coin = relationship("Coin", back_populates="prices")

class CoinsDAL:
    def __init__(self, session: Session):
        self.session = session
    def get_all_coins(self) -> List[Coin]:
        return self.session.query(Coin).all()
    def get_coin_by_symbol(self, symbol: str) -> Optional[Coin]:
        try:
            return self.session.query(Coin).filter(Coin.symbol == symbol).one()
        except NoResultFound:
            return None
    def update_coin_pnl(
        self, symbol: str, new_realized_pnl: Optional[float]
    ) -> Optional[Coin]:
        coin = self.get_coin_by_symbol(symbol)
        if coin:
            coin.realized_pnl = new_realized_pnl
            self.session.commit()
            return coin
        return None
    def add_price_to_coin(
        self, symbol: str, timestamp: datetime, value: float
    ) -> Optional[CoinPrice]:
        coin = self.get_coin_by_symbol(symbol)
        if coin:
            new_price = CoinPrice(timestamp=timestamp, value=value, symbol=coin.symbol)
            self.session.add(new_price)
            self.session.commit()
            return new_price
        return None
    def get_coin_prices_by_symbol(self, symbol: str) -> List[CoinPrice]:
        coin = self.get_coin_by_symbol(symbol)
        if coin:
            return (
                self.session.query(CoinPrice)
                .filter(CoinPrice.symbol == coin.id)
                .order_by(CoinPrice.timestamp)
                .all()
            )
        return []
    def get_current_price_for_coin(self, symbol: str) -> Optional[CoinPrice]:
        coin: Union[Coin, CoinPrice] = self.get_coin_by_symbol(symbol)
        if coin and coin.prices:
            # Get the most recent price directly from the related prices
            return max(coin.prices, key=lambda price: price.timestamp)
        return None
    def add_coin(
        self, symbol: str, coin_id: str, realized_pnl: Optional[float] = None
    ) -> Optional[Coin]:
        existing_coin = self.get_coin_by_symbol(symbol)
        if existing_coin:
            return None
        new_coin = Coin(
            symbol=symbol, coin_id=coin_id, realized_pnl=realized_pnl or 0.0, prices=[]
        )
        self.session.add(new_coin)
        self.session.commit()
        return new_coin

# Create Order Model
class PaperOrder(Base):
    __tablename__ = "paper_orders"
    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, nullable=False)
    buy_price = Column(Float, nullable=False)
    quantity = Column(Float, nullable=False)
    symbol = Column(String, nullable=False)
    direction = Column(String, nullable=False)
    direction: Literal[
        "BUY", "SELL"
    ]  # Type hinting for Python-side checking, not affecting DB schema

class OrdersDAL:
    def __init__(self, session: Session):
        self.session = session
    def insert_order(
        self,
        timestamp: datetime,
        buy_price: float,
        quantity: float,
        symbol: str,
        direction: str,
    ) -> PaperOrder:
        new_order = PaperOrder(
            timestamp=timestamp,
            buy_price=buy_price,
            quantity=quantity,
            symbol=symbol,
            direction=direction,
        )
        self.session.add(new_order)
        self.session.commit()
        return new_order
    def get_order_by_symbol(self, symbol: str) -> Optional[PaperOrder]:
        try:
            return (
                self.session.query(PaperOrder)
                .filter(PaperOrder.symbol == symbol)
                .order_by(PaperOrder.timestamp.desc())
                .first()
            )
        except NoResultFound:
            return None
    def get_all_orders(
        self, direction: Optional[Literal["BUY", "SELL"]] = None
    ) -> List[PaperOrder]:
        query = self.session.query(PaperOrder)
        if direction:
            query = query.filter(PaperOrder.direction == direction)
        return query.all()

# Create Portfolio Model
class PnLEntry(Base):
    __tablename__ = "pnl_entries"
    id = Column(Integer, primary_key=True, autoincrement=True)
    date = Column(DateTime, nullable=False)
    value = Column(Float, nullable=False)
    portfolio_item_id = Column(
        Integer, ForeignKey("portfolio_items.id"), nullable=False
    )
class PortfolioItem(Base):
    __tablename__ = "portfolio_items"
    id = Column(Integer, primary_key=True, autoincrement=True)
    cost_basis = Column(Float, nullable=False)
    total_quantity = Column(Float, nullable=False)
    symbol = Column(String, nullable=False)
    # Relationship with PnLEntry (One-to-Many: One PortfolioItem can have many PnLEntries)
    pnl_entries = relationship(
        "PnLEntry", backref="portfolio_item", cascade="all, delete"
    )

class PortfolioDAL:
    def __init__(self, session: Session):
        self.session = session
    def get_portfolio_item_by_symbol(self, symbol: str) -> Optional[PortfolioItem]:
        try:
            return (
                self.session.query(PortfolioItem)
                .filter(PortfolioItem.symbol == symbol)
                .one()
            )
        except NoResultFound:
            return None
    def insert_portfolio_item(
        self, symbol: str, cost_basis: float, total_quantity: float
    ) -> PortfolioItem:
        new_item = PortfolioItem(
            symbol=symbol, cost_basis=cost_basis, total_quantity=total_quantity
        )
        self.session.add(new_item)
        self.session.commit()
        return new_item
    def update_portfolio_item_by_symbol(
        self,
        symbol: str,
        cost_basis: float,
        additional_quantity: float,
    ) -> Optional[PortfolioItem]:
        portfolio_item = self.get_portfolio_item_by_symbol(symbol)
        if portfolio_item is None:
            return None
        portfolio_item.cost_basis = cost_basis
        portfolio_item.total_quantity += additional_quantity
        self.session.commit()
        return portfolio_item
    def add_pnl_entry_by_symbol(
        self, symbol: str, date: datetime, value: float
    ) -> Optional[PnLEntry]:
        portfolio_item = self.get_portfolio_item_by_symbol(symbol)
        if portfolio_item is None:
            return None
        pnl_entry = PnLEntry(
            date=date, value=value, portfolio_item_id=portfolio_item.id
        )
        self.session.add(pnl_entry)
        self.session.commit()
        return pnl_entry

